#!/usr/bin/env node
/**
 * Capture swipe-demo.html frames → swipe-demo.mp4 + swipe-demo.gif
 * Uses system Google Chrome (playwright-core channel) + system ffmpeg.
 */
import { chromium } from "/tmp/pw/package/index.mjs";
import { pathToFileURL } from "node:url";
import {
  mkdirSync,
  rmSync,
  existsSync,
  writeFileSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const htmlPath = join(root, "landing/ainews/assets/swipe-demo.html");
const outDir = join(root, "landing/ainews/assets");
const framesDir = join(root, ".tmp-swipe-frames");

rmSync(framesDir, { recursive: true, force: true });
mkdirSync(framesDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

const browser = await chromium.launch({
  channel: "chrome",
  headless: true,
});

const context = await browser.newContext({
  viewport: { width: 390, height: 844 },
  deviceScaleFactor: 2,
});
const page = await context.newPage();
await page.goto(pathToFileURL(htmlPath).href, { waitUntil: "networkidle" });
await page.waitForSelector('[data-ready="1"]', { timeout: 20000 }).catch(() => {});
await page.waitForTimeout(500);

const fps = 12;
const seconds = 8;
const total = fps * seconds;
for (let i = 0; i < total; i++) {
  const name = join(framesDir, `frame_${String(i).padStart(4, "0")}.png`);
  await page.screenshot({ path: name, type: "png" });
  await page.waitForTimeout(Math.round(1000 / fps));
  if (i % 12 === 0) process.stdout.write(`frame ${i}/${total}\n`);
}

await context.close();
await browser.close();

const mp4 = join(outDir, "swipe-demo.mp4");
const gif = join(outDir, "swipe-demo.gif");
const pattern = join(framesDir, "frame_%04d.png");

let res = spawnSync(
  "ffmpeg",
  [
    "-y",
    "-framerate",
    String(fps),
    "-i",
    pattern,
    "-an",
    "-c:v",
    "libx264",
    "-pix_fmt",
    "yuv420p",
    "-movflags",
    "+faststart",
    "-vf",
    "scale=390:844:flags=lanczos",
    mp4,
  ],
  { encoding: "utf8" }
);
if (res.status !== 0) {
  console.error(res.stderr.slice(-1200));
  process.exit(1);
}
console.log("Wrote", mp4);

res = spawnSync(
  "ffmpeg",
  [
    "-y",
    "-i",
    mp4,
    "-vf",
    "fps=10,scale=320:-1:flags=lanczos,split[s0][s1];[s0]palettegen=max_colors=96[p];[s1][p]paletteuse=dither=bayer",
    "-loop",
    "0",
    gif,
  ],
  { encoding: "utf8" }
);
if (res.status !== 0) {
  console.error(res.stderr.slice(-1200));
  process.exit(1);
}
console.log("Wrote", gif);

rmSync(framesDir, { recursive: true, force: true });
writeFileSync(
  join(outDir, "swipe-demo.txt"),
  "Generated by scripts/record-swipe-demo.mjs from real feed article copy.\n",
  "utf8"
);
console.log("done");
